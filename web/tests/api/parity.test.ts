const py = readFileSync(fileURLToPath(new URL('../../../backend/app/mock.py', import.meta.url)), 'utf8');
const jsRe = (s: string) => s.replace(/\(\?P</g, '(?<');
const rawStr = (name: string): string => {
  const m = new RegExp(String.raw`^${name} = re\.compile\(r"(.*)"\)\s*$`, 'm').exec(py);
  if (!m) throw new Error(`mock.py: ${name} not found`);
  return jsRe(m[1]);
};
const pairs = (name: string): Array<[string, string]> => {
  const m = new RegExp(String.raw`^${name} = \[(.*)\]\s*$`, 'm').exec(py);
  if (!m) throw new Error(`mock.py: ${name} not found`);
  return [...m[1].matchAll(/\(r"([^"]*)", "(\w+)"\)/g)].map((x) => [jsRe(x[1]), x[2]]);
};

describe('mock.py drift guard', () => {
  it('keyword lists match', () => {
    const block = /KEYWORDS: dict\[str, list\[str\]\] = \{(.*?)^\}/ms.exec(py)![1];
    const parsed: Record<string, string[]> = {};
    for (const m of block.matchAll(/"([a-z-]+)": \[(.*?)\]/g)) parsed[m[1]] = [...m[2].matchAll(/"([a-z]+)"/g)].map((x) => x[1]);
    expect(KEYWORDS).toEqual(parsed);
  });
  it('regex sources match', () => {
    expect(NEAR_THIS.source).toBe(rawStr('NEAR_THIS'));
    expect(ON_THIS.source).toBe(rawStr('ON_THIS'));
    expect(ADD.source).toBe(rawStr('ADD'));
    expect(REMOVE.source).toBe(rawStr('REMOVE'));
    expect(LANDMARK.source).toBe(rawStr('LANDMARK'));
    expect(STRUCTURE.source).toBe(rawStr('STRUCTURE'));
    expect(TIME.map(([r, v]) => [r.source, v])).toEqual(pairs('TIME_WORDS'));
    expect(WEATHER.map(([r, v]) => [r.source, v])).toEqual(pairs('WEATHER_WORDS'));
    expect(INTERACT.map(([r, v]) => [r.source, v])).toEqual(pairs('INTERACTIONS'));
    const atmos = /ATMOS_NOUNS = \{(.*)\}/.exec(py)![1];
    expect([...ATMOS]).toEqual([...atmos.matchAll(/"([a-z]+)"/g)].map((x) => x[1]));
  });
});

describe('sha256 + seed', () => {
  it('matches standard vectors', () => {
    expect(sha256Hex('')).toBe('e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855');
    expect(sha256Hex('abc')).toBe('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
    expect(sha256Hex('a'.repeat(1000))).toHaveLength(64);
  });
  // Expected from: python -c "int(hashlib.sha256(p.strip().lower().encode()).hexdigest()[:8],16)&0x7FFFFFFF" in backend/.venv
  it.each([
    ['a misty valley', 1563187181],
    ['Frozen Mountains With A Castle  ', 2007134721],
    ['tropical island with a lighthouse', 2047560744],
  ])('offline seed equals Python prompt_seed for %j', (prompt, seed) => {
    const w = localWorld(prompt);
    expect(w.type === 'recipe' && w.recipe.seed).toBe(seed);
  });
});

